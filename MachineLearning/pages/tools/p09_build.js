// p09_build.js — 生成 09_alignment.lab.js 里的 P06_DATA（SFT checkpoint + 偏好候选回答）
// 用 09_alignment.lab.js 里同一份 SFT 代码（P06.sftInit / sftStep）、默认设置训练 400 步；
// 再从得到的 checkpoint（float16 往返后）按固定规则挑出每个问题的 6 种候选回答。
// 用法（在 pages/ 下）：node tools/p09_build.js
const fs = require('fs');
const path = require('path');
global.LM = require('../llm_common.js');
global.LM_WEIGHTS = require('../llm_weights.js');
global.PipelineLab = global.PL = { mount() {} };
const LAB = path.join(__dirname, '..', '09_alignment.lab.js');
const { P06 } = require(LAB);
const { AG, V, A, Q, SFT, K, TM } = P06;
const fact = P06.fact, attrOf = P06.attrOf;

const t0 = Date.now();
const base = LM.gpt.loadWeights(LM.gpt.create(LM_WEIGHTS.base.cfg, 1), LM_WEIGHTS.base.b64);
const st = P06.sftInit(base, { hold: 'pair', lr: SFT.lr, mix: SFT.mix });
while (st.step < SFT.steps) { P06.sftStep(st); if (st.step % SFT.evalEvery === 0) P06.sftEval(st); }
const ev = st.evals[st.evals.length - 1];
console.log(`SFT ${SFT.steps} steps in ${((Date.now() - t0) / 1000).toFixed(1)} s: train exact ${ev.trainExact.toFixed(3)} held exact ${ev.heldExact.toFixed(3)} | P(canonical) train ${ev.trainP.toFixed(3)} held ${ev.heldP.toFixed(3)} | pretrain val ${ev.pre.toFixed(3)} (base ${P06.preValLoss(base).toFixed(3)})`);
const b64 = LM.gpt.exportWeights(st.m);
const ref = LM.gpt.loadWeights(LM.gpt.create(LM_WEIGHTS.base.cfg, 1), b64);
const evR = P06.evalTF(ref, P06.EX);
console.log('after f16 round trip: held P(canonical)', LM.mean(evR.filter((_, i) => P06.EX[i].held).map((r) => Math.exp(r.logp))).toFixed(3));

// 候选回答（规则见 P06.TYPE_TIP）
const lp = (e, s) => P06.seqLogProbs(ref, [{ P: e.prompt, R: V.encode(s) }])[0];
const best = (e, list) => list.reduce((b, s) => { const v = lp(e, s); return !b || v > b.v ? { s, v } : b; }, null).s;
const cands = P06.EX.map((e) => {
    const { a, q } = e, others = A.map((_, i) => i).filter((i) => i !== a);
    const c1 = best(e, others.map((a2) => fact(a2, q) + '<eos>'));
    const vals = [...new Set(A.map((_, i) => attrOf(i, q)).filter((v) => v !== attrOf(a, q)))];
    const key = ['food', 'home', 'color'][q];
    const c2 = best(e, vals.map((v) => Q[q].a(Object.assign({}, A[a], { [key]: v })) + '<eos>'));
    const c3 = best(e, [0, 1, 2].filter((q2) => q2 !== q).map((q2) => fact(a, q2) + '<eos>'));
    const c4 = best(e, [0, 1, 2].filter((q2) => q2 !== q).map((q2) => fact(a, q) + fact(a, q2) + '<eos>'));
    const pre = [...e.prompt, ...V.encode(fact(a, q))];
    const g = LM.gpt.generate(base, pre, TM - pre.length, { greedy: true });
    const c5 = fact(a, q) + V.decode(g.gen.filter((i) => i > 3));
    return [fact(a, q) + '<eos>', c1, c2, c3, c4, c5];
});
const maxLen = Math.max(...P06.EX.map((e, pi) => Math.max(...cands[pi].map((s) => e.prompt.length + V.encode(s).length))));
console.log('candidates ok, longest sequence', maxLen, 'tokens; example:', cands[14].join(' | '));
const data = { sft: b64, cands, meta: { steps: SFT.steps, trainExact: +ev.trainExact.toFixed(3), heldExact: +ev.heldExact.toFixed(3), heldP: +ev.heldP.toFixed(3), trainP: +ev.trainP.toFixed(3), pre: +ev.pre.toFixed(3) } };
let src = fs.readFileSync(LAB, 'utf8');
const line = `const P06_DATA = ${JSON.stringify(data)};   // generated by tools/p09_build.js`;
src = src.replace(/^const P06_DATA = .*$/m, () => line);
fs.writeFileSync(LAB, src);
console.log('wrote P06_DATA into', path.basename(LAB), (line.length / 1024).toFixed(0), 'KB', ((Date.now() - t0) / 1000).toFixed(1), 's');
