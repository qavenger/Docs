const IX = (() => {
    const W = 140, H = 168;
    // view the curtain from the side its tips drape toward (yaw = π): strands lean toward the viewer like hair over the crown,
    // so front-top light forms a highlight band (same setup as module 01)
    const cam = HAIR.ortho({ yaw: Math.PI, center: [0, -7.2, 0], size: 17.5 });
    const lightDir = (S) => {   // camera-relative: az = 0 → from the viewer, ±180 → from behind the hair; el > 0 → from above
        const az = S.lightAz * Math.PI / 180, el = S.lightEl * Math.PI / 180, ce = Math.cos(el), R = cam.right, V = cam.toViewer, U = cam.up;
        return HAIR.norm([0, 1, 2].map((k) => ce * (Math.sin(az) * R[k] + Math.cos(az) * V[k]) + Math.sin(el) * U[k]));
    };
    const BG = [0.03, 0.035, 0.045];
    return { W, H, cam, lightDir, BG };
})();
