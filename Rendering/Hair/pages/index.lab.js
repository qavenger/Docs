// guides vs strands, projected with the shared camera (vector drawing)
function drawGroom(c, S) {
    const { ctx, w, h } = PL.draw.ctx(c), cam = IX.cam;
    const P = (x, y, z) => { const p = HAIR.project(cam, [x, y, z], w, h); return [p[0], p[1]]; };
    ctx.lineWidth = 0.5; ctx.strokeStyle = 'rgba(150,180,210,0.35)';
    S.groom.strands.forEach((s, k) => { if (k % 3) return; ctx.beginPath(); for (let i = 0; i < s.p.length; i += 3) { const [x, y] = P(s.p[i], s.p[i + 1], s.p[i + 2]); if (i) ctx.lineTo(x, y); else ctx.moveTo(x, y); } ctx.stroke(); });
    ctx.lineWidth = 2; ctx.strokeStyle = '#e0a060';
    S.groom.guides.forEach((g) => { ctx.beginPath(); for (let i = 0; i < g.p.length; i += 3) { const [x, y] = P(g.p[i], g.p[i + 1], g.p[i + 2]); if (i) ctx.lineTo(x, y); else ctx.moveTo(x, y); } ctx.stroke(); });
    ctx.fillStyle = '#888'; ctx.font = '10px Consolas, monospace'; ctx.fillText(`${S.groom.guides.length} guides → ${S.groom.strands.length} strands`, 6, 14);
}
// one clump (strands of guide 3) rasterized in its own front view = what a card bake stores in the coverage channel
function drawCardBake(c, S) {
    const clump = S.groom.strands.filter((s) => s.guide === 3), g = S.groom.guides[3];
    const cx = g.p[3 * 12], cz = g.p[3 * 12 + 2];
    const r = HAIR.raster(clump, HAIR.ortho({ center: [cx, -7, cz], size: 16 }), 64, 128, { widthScale: 2 });
    PL.draw.field(c, r.alpha, 64, 128, { range: [0, 1], map: 'gray' });
}
